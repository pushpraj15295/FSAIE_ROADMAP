# pip is a package manager for Python.
# Python has many external libraries that developers use instead of writing everything from scratch.

# pip is used to install, uninstall, and manage these external libraries.

# How to install a package using pip?
# pip install package_name

# python3 -m pip install requests
# This will install the latest version of requests.

# Example: pip install django
# This will install the latest version of Django.

# How to uninstall a package using pip?
# pip uninstall package_name
# Example: pip uninstall django
# This will uninstall the latest version of Django.


# How to update a package using pip?
# pip install --upgrade package_name
# Example: pip install --upgrade django
# This will update the latest version of Django.

# How to list all packages using pip?
# pip list
# Example: pip list
# This will list all packages installed in the current environment.



