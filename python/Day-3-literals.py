# Literals 

# these are 4 types of literals in python.

#  Numeric Literals - these are the numbers in python. we can use these numbers in our program.
#  String Literals - these are the strings in python. we can use these strings in our program.
#  Boolean Literals - these are the boolean values in python. we can use these boolean values in our program.
#  Special Literals - these are the special values in python    


#  Numeric literals we can take in 4 types in python. -------------------------

a = 10 # Decimal Literal
b = 0b1010 # Binary Literal
c = 0o12 # Octal Literal
d = 0xA # Hexadecimal Literal


#  float literals we can take in 2 types in python.
e = 10.5 # Decimal Literal
f = 1.5e2 # Exponential Literal 


#  String literals we can take in 5 types in python.--------------------------
g = "Hello, World!" # Double Quotes
h = 'Hello, World!' # Single Quotes
i = """Hello, 
     hi 
     World!""" # Triple Quotes
j = r"Hello, World!" # Raw String
k = u"Hello, World!" # Unicode String



#  Boolean literals we can take in 2 types in python. -----------------------
l = True # True
m = False # False


#  Special literals we can take in 1 type in python. -------------------------


n = None 
# None - if we want to assign a variable with no value then we can use None. 
# it is used to represent the absence of a value or a null value.





