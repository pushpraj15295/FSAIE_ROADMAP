# loops used to repeat a block of code multiple times.
#  There are two types of loops in Python: for loops and while loops.

# while loop in python -----------------------------
i = 1
while i <= 5:
    print(i)
    print("multiple of 2", i * 2)
    i += 1  


# for loop in python --------------------------------
arr = [1, 2, 3, 4, 5,67, 8, 9, 10]
for i in arr:
    print(i)    