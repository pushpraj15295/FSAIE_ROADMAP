# Basic Data Types in Python -----------------------

# integer
print(10)
print(1e308) # big number
print(1e309) # infinity

# float 
print(10.5)
print(10.9)

# boolean
print(True)
print(False)

# string
print("Hello, World!")

# complex
print(1 + 2j)

# Container Data Types in Python -----------------------

# list - ordered collection of elements [ Array ]
print([1, 2, 3, 4, 5])

# tuple - ordered collection of elements ( Immutable )
print((1, 2, 3, 4, 5))

# set - unordered collection of unique elements 
print({1, 2, 3, 4, 5})

# dictionary - objects with key-value pairs
print({"name": "John", "age": 30})

